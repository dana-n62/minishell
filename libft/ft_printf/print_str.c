#include "ft_printf.h"

void	print_str(char *str, int *size)
{
	if (!str)
	{
		write(1, "(null)", 6);
		*size += 6;
		return ;
	}
	while (*str != '\0')
	{
		write(1, &*str, 1);
		*size += 1;
		str++;
	}
}
